"""Markdown mirrors of the JSON records. Generated, never parsed back."""

from __future__ import annotations

from datetime import datetime

from .model import BREAK, DONE, MOVED, ROLLED, RUNNING, SKIPPED, STASHED, Day, Item, Stash
from .parse import format_minutes
from .schedule import Slot


def _label(item: Item) -> str:
    title = f"☕ Break: {item.title}" if item.kind == BREAK else item.title
    if item.fixed_start:
        title += "  📌"
    if item.extensions:
        title += f"  (+{format_minutes(sum(item.extensions))})"
    if item.tags:
        title += "  " + " ".join(f"#{t}" for t in item.tags)
    return title


def _notes(item: Item) -> list[str]:
    return [f"    {line}" for line in item.notes.splitlines() if line.strip()]


def render_day(day: Day, slots: list[Slot], now: datetime) -> str:
    lines = [f"# {day.date:%A, %d %b %Y}", ""]
    by_uid = {s.item.uid: s for s in slots}

    for item in day.items:
        slot = by_uid.get(item.uid)
        span = f"{slot.start:%H:%M} - {slot.end:%H:%M}" if slot and (slot.end > slot.start or item.actual_start) else "--:-- - --:--"
        label = _label(item)
        if item.status == DONE:
            lines.append(f"- [x] {span}  {label}")
        elif item.status == RUNNING:
            lines.append(f"- [ ] {span}  **{label}**  ⏳ running")
        elif item.status == SKIPPED:
            lines.append(f"- [ ] ~~{label}~~  (skipped)")
        elif item.status == ROLLED:
            lines.append(f"- [ ] ~~{label}~~  → rolled to {item.target}")
        elif item.status == MOVED:
            lines.append(f"- [ ] ~~{label}~~  → moved to {item.target}")
        elif item.status == STASHED:
            lines.append(f"- [ ] ~~{label}~~  → stashed")
        else:
            lines.append(f"- [ ] {span}  {label}")
        lines.extend(_notes(item))

    tasks = [i for i in day.active if i.kind != BREAK and i.status != SKIPPED]
    done = [i for i in tasks if i.status == DONE]
    focus = sum(s.minutes for s in slots if s.item.kind != BREAK and s.item.status == DONE)
    breaks = sum(s.minutes for s in slots if s.item.kind == BREAK)
    lines += [
        "",
        f"Done {len(done)}/{len(tasks)} · Focus {format_minutes(focus)} · Breaks {format_minutes(breaks)}",
        "",
        f"<!-- generated by kde-todo at {now:%Y-%m-%d %H:%M}. Edit the .json, not this file. -->",
        "",
    ]
    return "\n".join(lines)


def render_stash(stash: Stash) -> str:
    lines = ["# Stash", ""]
    for item in stash.items:
        source = f"  (from {item.origin})" if item.origin else ""
        lines.append(f"- [ ] {item.id}. {_label(item)} · {format_minutes(item.duration)}{source}")
        lines.extend(_notes(item))
    if not stash.items:
        lines.append("_Empty._")
    lines.append("")
    return "\n".join(lines)
